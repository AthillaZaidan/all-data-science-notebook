cells.append(md(
    "## Patch Evidence Maps\n\n"
    "Both models score an image through a linear function of the mean patch token, so each patch's "
    "contribution to a class logit can be read off exactly: it is the dot product of that patch's "
    "token with the head weights for the mean-patch half of the feature (scaled by the standardiser "
    "for the probe, or by the head layer norm for the fine-tuned model), centred on the image's "
    "average patch. Red patches push toward the "
    "predicted class, blue patches against it. This is exact for the linear head, with no gradients "
    "or sampling, and shows whether the model looks at the object or at background shortcuts."
))

cells.append(code(
    "def evidence_weights(c):\n"
    "    if SELECTED != 'probe' and FT_MODEL is not None:\n"
    "        model = FT_MODEL\n"
    "        w = model.head.weight.detach().float().cpu().numpy()[0 if IS_REG else c]\n"
    "        g = model.norm.weight.detach().float().cpu().numpy()\n"
    "        return model.backbone, (w * g)[HIDDEN:], 'fine-tuned'\n"
    "    scaler, clf = PROBE_FULL[0], PROBE_FULL[-1]\n"
    "    if IS_ML:\n"
    "        est = clf.estimators_[c]\n"
    "        coef = est.coef_[0] if hasattr(est, 'coef_') else np.zeros(2 * HIDDEN)\n"
    "    elif IS_REG:\n"
    "        coef = clf.coef_.ravel()\n"
    "    elif clf.coef_.shape[0] == 1:\n"
    "        coef = clf.coef_[0] * (1 if c == 1 else -1)\n"
    "    else:\n"
    "        coef = clf.coef_[c]\n"
    "    return frozen, (coef / scaler.scale_)[HIDDEN:], 'linear probe'\n"
    "\n"
    "if HAS_HOLD:\n"
    "    picks = list(rng.choice(HOLD, min(8, len(HOLD)), replace=False))\n"
    "    ph = FINAL['hold']\n"
    "    pos_h = {i: j for j, i in enumerate(HOLD)}\n"
    "    fig, axes = plt.subplots(2, len(picks), figsize=(len(picks) * 2.3, 5))\n"
    "    axes = np.atleast_2d(axes.T).T if len(picks) == 1 else axes\n"
    "    for j, i in enumerate(picks):\n"
    "        p = ph[pos_h[i]]\n"
    "        c = 0 if IS_REG else int(np.argmax(p))\n"
    "        model, w, src = evidence_weights(c)\n"
    "        model.to(DEVICE)\n"
    "        tok = patch_tokens(model, [PATHS[i]])[0]\n"
    "        ev = tok @ w\n"
    "        # the mean over patches is a per-image constant shared by every patch, so only deviations from it localise evidence\n"
    "        ev = (ev - ev.mean()).reshape(GRID, GRID)\n"
    "        lim = np.abs(ev).max() + 1e-8\n"
    "        img = load_rgb(PATHS[i]).resize((IMG_SIZE, IMG_SIZE))\n"
    "        axes[0, j].imshow(img)\n"
    "        axes[1, j].imshow(img)\n"
    "        axes[1, j].imshow(ev, cmap='coolwarm', vmin=-lim, vmax=lim, alpha=0.55, extent=(0, IMG_SIZE, IMG_SIZE, 0), interpolation='bilinear')\n"
    "        true = f'{Y[i]:.3g}' if IS_REG else ', '.join(CLASS_NAMES[k] for k in np.where(Y[i] > 0)[0][:2]) if IS_ML else CLASS_NAMES[Y[i]]\n"
    "        guess = f'{p:.3g}' if IS_REG else f'{CLASS_NAMES[c]} {p[c]:.2f}'\n"
    "        axes[0, j].set_title(f'true: {str(true)[:16]}', fontsize=8)\n"
    "        axes[1, j].set_title(f'pred: {guess[:18]}', fontsize=8)\n"
    "        for ax in axes[:, j]:\n"
    "            ax.axis('off')\n"
    "    model.to('cpu')\n"
    "    fig.suptitle(f'Patch evidence for the predicted class ({src}); red supports, blue opposes', fontweight='bold')\n"
    "    save_fig(fig, 'patch evidence maps')"
))


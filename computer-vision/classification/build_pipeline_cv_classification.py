    "horizontal flip, `'medium'` adds colour jitter and small rotations, and `'strong'` adds "
    "TrivialAugment and random erasing. `VFLIP = True` adds vertical flips for images without a "
    "natural orientation (satellite, microscopy). Evaluation resizes to a square input only."

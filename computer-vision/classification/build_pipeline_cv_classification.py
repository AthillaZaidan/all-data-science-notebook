    "*A holdout set is separated first and touched only once at the end. Exact duplicate images are "
    "grouped so they never straddle a fold. The image representation is the DINOv3 class token "
    "concatenated with the mean of the patch tokens, which is the standard DINO linear-evaluation "
    "feature.*\n\n"
    "```\n"
    "Images -> header check -> duplicate hashing -> holdout split -> grouped CV folds\n"
    "    |\n"
    "    +-- Baseline   : frozen DINOv3 -> [CLS ; mean(patches)] (flip TTA, cached)\n"
    "    |                 -> standardise -> Logistic / Ridge, C tuned by CV    -> pipeline-output/baseline/\n"
    "    +-- Fine-tune  : DINOv3 (last N blocks trainable, LLRD) -> LayerNorm -> dropout -> linear head\n"
    "    |                 augmentation, AdamW + cosine warmup, mixed precision, early stopping, flip TTA\n"
    "    +-- Ensemble   : weight blend on out-of-fold predictions, decision rule tuned on OOF\n"
    "         |\n"
    "    Best by CV -> holdout evaluation -> patch-feature maps -> error analysis\n"
    "         -> pipeline-output/final/ (submission, predictions, report, decisions)\n"
    "```"

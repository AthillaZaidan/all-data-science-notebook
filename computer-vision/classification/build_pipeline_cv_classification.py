    "    if CFG.AUGMENT == 'strong':\n"
    "        aug += [T.TrivialAugmentWide()]\n"
    "    tail = [T.RandomErasing(p=0.25)] if CFG.AUGMENT == 'strong' else []\n"
    "    return T.Compose(aug + norm + tail)\n"

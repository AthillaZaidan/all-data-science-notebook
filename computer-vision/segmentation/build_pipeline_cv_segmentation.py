    "        add(final_norm(bb).parameters(), CFG.LR)\n"
    "    if n == L:\n"
    "        seen = {id(p) for g in groups for p in g['params']}\n"
    "        add([p for p in bb.parameters() if id(p) not in seen], CFG.LR * CFG.LLRD ** L)\n"

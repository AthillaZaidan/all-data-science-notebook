    "    paths = paths if paths is not None else [PATHS[i] for i in idx]\n"
    "    out = np.zeros((len(paths), N_OUT, STORE_SIZE, STORE_SIZE), np.uint8)\n"
    "    pos = 0\n"
    "    for x, _ in make_loader(paths=paths, batch_size=CFG.BATCH_SIZE):\n"

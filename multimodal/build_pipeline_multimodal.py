    "final_table = pd.DataFrame({'naive': score_all(EVAL_Y, naive_eval),\n"
    "                            'baseline': score_all(EVAL_Y, EVAL_P['baseline']),\n"
    "                            BEST_NAME: score_all(EVAL_Y, EVAL_P[BEST_NAME])})\n"
    "sign = 1 if GREATER_IS_BETTER[METRIC] else -1\n"
    "\n"

    "Category levels are fixed from the development set, so every fold, the holdout, and the test "
    "set share an identical category mapping. Levels outside the most frequent "
    "`GBM_MAX_CAT_LEVELS - 1` are pooled into `(other)`, which also absorbs levels unseen at "
    "training time."

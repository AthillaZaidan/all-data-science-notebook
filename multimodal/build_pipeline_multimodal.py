cells.append(md(
    "## Metric\n\n"
    "***RMSE** is the default regression metric. It penalises large errors quadratically and is "
    "reported together with MAE and R-squared, which explains the share of target variance captured.*\n\n"
    "$$\\text{RMSE} = \\sqrt{\\frac{1}{n}\\sum_{i=1}^{n}(y_i - \\hat{y}_i)^2} \\qquad "
    "R^2 = 1 - \\frac{\\sum_i (y_i - \\hat{y}_i)^2}{\\sum_i (y_i - \\bar{y})^2}$$\n\n"
    "***ROC AUC** is the default for binary classification because it is threshold-free and robust "
    "to imbalance. **Macro F1** is the default for multiclass because it weights every class equally.*\n\n"
    "$$\\text{Macro F1} = \\frac{1}{K}\\sum_{k=1}^{K} \\frac{2 \\cdot P_k \\cdot R_k}{P_k + R_k}$$"
))


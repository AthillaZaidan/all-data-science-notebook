    "class GBMModel:\n"
    "    kind = None\n"
    "\n"
    "    def __init__(self, params=None):\n"
    "        self.params = {**self.defaults(), **CFG.MODEL_PARAMS.get(self.kind, {}), **(params or {})}\n"
    "\n"
    "    def fit(self, X, y, X_valid=None, y_valid=None):\n"

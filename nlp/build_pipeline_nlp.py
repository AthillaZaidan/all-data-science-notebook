    "        out['actual'] = ([ml_names(r) for r in truth] if IS_ML else np.array(CLASS_NAMES, dtype=object)[np.asarray(truth).astype(int)]\n"
    "                         if IS_ORD else truth if IS_REG else LE.inverse_transform(truth))\n"
    "    if IS_ORD:\n"

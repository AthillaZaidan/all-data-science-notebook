    "$$\\text{Macro F1} = \\frac{1}{K}\\sum_{k=1}^{K} \\frac{2 \\cdot P_k \\cdot R_k}{P_k + R_k} \\qquad "
    "\\text{RMSE} = \\sqrt{\\frac{1}{n}\\sum_{i=1}^{n}(y_i - \\hat{y}_i)^2}$$"

    "to_json(FINAL, CFG.FINAL_DIR / 'final_metrics.json')\n"
    "plot_diagnostics(EVAL_Y, EVAL_P[BEST_NAME], f'Final model ({BEST_NAME}) {EVAL_NAME} diagnostics', 'final',\n"

    "def prediction_frame(pred, frame=None, truth=None):\n"
    "    out = pd.DataFrame(index=range(len(pred)))\n"
    "    if frame is not None and 'id' in frame.columns:\n"
    "        out[CFG.ID_COL or 'id'] = frame['id'].values\n"

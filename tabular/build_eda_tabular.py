    "def psi(expected, actual, bins=10):\n"
    "    edges = np.unique(np.quantile(expected.dropna(), np.linspace(0, 1, bins + 1)))\n"
    "    if len(edges) < 3:\n"
    "        return 0.0\n"
    "    e = np.histogram(np.clip(expected.dropna(), edges[0], edges[-1]), edges)[0] / expected.notna().sum()\n"
